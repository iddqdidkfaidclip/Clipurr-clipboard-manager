def unit(value: str) -> dict:
    return {"stringUnit": {"state": "translated", "value": value}}


def build_xcstrings(keys: list[str], translations: dict[str, list[str]]) -> dict:
    strings: dict = {}
    for i, key in enumerate(keys):
        locs = {"en": unit(key)}
        for lang, vals in translations.items():
            locs[lang] = unit(vals[i])
        strings[key] = {"localizations": locs}
    return {"sourceLanguage": "en", "strings": strings, "version": "1.0"}


def build_info_plist() -> dict:
    locs = {"en": unit(INFO_PLIST_EN)}
    for lang, value in INFO_PLIST_T.items():
        locs[lang] = unit(value)
    return {
        "sourceLanguage": "en",
        "strings": {INFO_PLIST_KEY: {"localizations": locs}},
        "version": "1.0"}


def remap_translations() -> dict[str, list[str]]:
    """Map legacy parallel arrays onto the live EN key list."""
    remapped: dict[str, list[str]] = {}
    for lang in LOCALES:
        assert len(T[lang]) == len(LEGACY_EN), f"{lang}: {len(T[lang])} != {len(LEGACY_EN)}"
        legacy_map = dict(zip(LEGACY_EN, T[lang]))
        values: list[str] = []
        for key in EN:
            if key in NEW_KEY_TRANSLATIONS and lang in NEW_KEY_TRANSLATIONS[key]:
                values.append(NEW_KEY_TRANSLATIONS[key][lang])
                continue
            lookup = KEY_ALIASES.get(key, key)
            values.append(legacy_map.get(lookup, key))
        remapped[lang] = values
    return remapped


